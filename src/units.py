"""Единицы проекта и пересчёт воды между слоем (мм) и объёмом (м³).

Правило проекта: площадь в га, вода в м³. Слой воды 1 мм на 1 га = 10 м³
(1 мм = 0.001 м, 1 га = 10 000 м², 0.001 × 10 000 = 10).
Все пересчёты мм <-> м³ делаются только здесь.
"""

import numpy as np

M3_PER_MM_HA = 10.0

# Единицы, которые разрешены в колонке unit файлов data/*.csv.
KNOWN_UNITS = {
    "ha": "гектар",
    "m3": "кубический метр",
    "mm": "миллиметр слоя воды",
    "mm/day": "миллиметр слоя воды в сутки",
    "m3/ha": "кубический метр на гектар",
    "degC": "градус Цельсия",
    "%": "процент",
    "m/s": "метр в секунду",
    "MJ/m2/day": "мегаджоуль на м² в сутки",
    "kPa": "килопаскаль",
    "h": "час",
    "day": "сутки (длительность)",
    "doy": "номер дня в году (1-366)",
    "m": "метр",
    "t": "тонна",
    "t/ha": "тонна на гектар",
    "KZT/t": "тенге за тонну",
    "KZT/ha": "тенге на гектар",
    "fraction": "доля от 0 до 1",
    "-": "безразмерная величина (например, Kc)",
}


def is_known_unit(unit: str) -> bool:
    """True, если единица есть в списке разрешённых."""
    return unit in KNOWN_UNITS


def mm_to_m3(mm, area_ha=1.0):
    """Слой воды (мм) на площади (га) -> объём (м³). При area_ha=1 даёт м³/га."""
    return np.asarray(mm, dtype=float) * np.asarray(area_ha, dtype=float) * M3_PER_MM_HA


def m3_to_mm(m3, area_ha=1.0):
    """Объём (м³) на площади (га) -> слой воды (мм). Площадь должна быть > 0."""
    area = np.asarray(area_ha, dtype=float)
    if np.any(area <= 0):
        raise ValueError("Площадь должна быть больше нуля, чтобы перевести м³ в мм")
    return np.asarray(m3, dtype=float) / (area * M3_PER_MM_HA)
